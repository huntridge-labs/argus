"""Generate ``.ai/index.yaml`` and fail CI when the committed copy drifts.

The index lists the keys of every ``.ai/`` file so an agent can find the
entry it needs without loading the file whole. It used to come from the
AICaC action, but that action's index step pushes unsigned commits, which
the signed-commits ruleset rejects, so it stayed off and the index went
stale (ADR-555). This script builds it from the files themselves instead.

Run as:
    python -m scripts.ci.check_ai_index          # exit 1 if index.yaml is stale
    python -m scripts.ci.check_ai_index --fix    # regenerate it in place
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from scripts.ci.adr_records import adr_number, load_legacy, load_records

INDEX_FILE = Path(".ai/index.yaml")
HEADER = (
    "# AUTO-GENERATED by `python -m scripts.ci.check_ai_index --fix`. Do not hand-edit.\n"
)
FIX_HINT = "Run: python -m scripts.ci.check_ai_index --fix"

# Where to look for each kind of question. Paths are relative to .ai/.
ROUTING = {
    "project_overview": ["context.yaml"],
    "architecture": ["architecture.yaml"],
    "how_to": ["workflows.yaml"],
    "why_decision": ["decisions.yaml", "decisions/"],
    "error_troubleshooting": ["errors.yaml"],
    "deep_architecture": ["architecture.yaml", "decisions.yaml", "decisions/"],
}


def _load(root: Path, name: str) -> dict[str, Any]:
    path = root / ".ai" / name
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
    if not isinstance(data, dict):
        raise ValueError(f".ai/{name}: expected a mapping at the top level")
    return data


def _keys(mapping: Any) -> list[str]:
    return sorted(str(k) for k in mapping) if isinstance(mapping, dict) else []


def _adr_ids(store: dict[str, Any]) -> list[str]:
    return sorted(store, key=lambda adr_id: adr_number(adr_id) or 0)


def build_index(root: Path) -> dict[str, Any]:
    """Return the index for the ``.ai/`` directory under ``root``."""
    context = _load(root, "context.yaml")
    architecture = _load(root, "architecture.yaml")
    workflows = _load(root, "workflows.yaml")
    errors = _load(root, "errors.yaml")

    problems: list[str] = []
    legacy = load_legacy(root, problems)
    records = load_records(root, problems)
    if problems:
        raise ValueError("ADR stores are invalid:\n  " + "\n  ".join(problems))

    project = context.get("project") or {}
    return {
        "version": str(context.get("version", "")),
        "summary": " ".join(str(project.get("description", "")).split()),
        "keys": {
            "context": [k for k in _keys(context) if k not in ("version", "schema")],
            "architecture": _keys(architecture.get("components")),
            "workflows": _keys(workflows.get("workflows")),
            "decisions": _adr_ids(legacy),
            "decision_records": _adr_ids(records),
            "errors": _keys(errors.get("errors")),
        },
        "routing": ROUTING,
    }


def render(index: dict[str, Any]) -> str:
    body = yaml.safe_dump(index, sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fix", action="store_true", help="regenerate .ai/index.yaml in place")
    parser.add_argument(
        "--repo-root", type=Path, default=Path("."),
        help="repo root containing .ai/ (default: cwd)",
    )
    args = parser.parse_args(argv)
    root: Path = args.repo_root.resolve()

    try:
        expected = render(build_index(root))
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR: could not build {INDEX_FILE}: {exc}", file=sys.stderr)
        return 2

    path = root / INDEX_FILE
    if args.fix:
        path.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Updated {INDEX_FILE}")
        return 0

    if not path.exists():
        print(f"ERROR: {INDEX_FILE} does not exist.\n{FIX_HINT}", file=sys.stderr)
        return 1
    if path.read_text(encoding="utf-8") != expected:
        print(
            f"ERROR: {INDEX_FILE} is out of date with the .ai/ files it indexes.\n{FIX_HINT}",
            file=sys.stderr,
        )
        return 1

    print(f"{INDEX_FILE} is up to date.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
