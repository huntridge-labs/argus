"""CLI side of SBOM matcher routing (#493): dry-run plan and the nudge."""

from __future__ import annotations

from pathlib import Path

import pytest

from argus.cli import EXIT_SUCCESS, _sbom_planned_scanners, build_parser, cmd_scan
from argus.core.sbom import detect_sbom

FIXTURES = Path(__file__).resolve().parents[2] / "tests" / "fixtures" / "sbom"


def _dry_run(tmp_path, monkeypatch, capsys, *extra):
    monkeypatch.chdir(tmp_path)
    args = build_parser().parse_args(["scan", *extra, "--dry-run"])
    assert cmd_scan(args) == EXIT_SUCCESS
    return capsys.readouterr().out


class TestDryRunPlan:
    def test_syft_sbom_plans_grype_and_osv(self, tmp_path, monkeypatch, capsys):
        out = _dry_run(
            tmp_path, monkeypatch, capsys, "--sbom", str(FIXTURES / "syft-amzn2023.spdx.json"),
        )
        assert "Scanners:    grype, osv" in out
        assert "SBOM generated by syft 1.54.1" in out

    def test_trivy_sbom_plans_osv_and_trivy(self, tmp_path, monkeypatch, capsys):
        out = _dry_run(
            tmp_path, monkeypatch, capsys, "--sbom", str(FIXTURES / "trivy-amzn2023.cdx.json"),
        )
        assert "Scanners:    osv, trivy" in out

    def test_explicit_matcher_is_planned_with_a_warning(self, tmp_path, monkeypatch, capsys):
        out = _dry_run(
            tmp_path, monkeypatch, capsys,
            "trivy", "--sbom", str(FIXTURES / "syft-amzn2023.spdx.json"),
        )
        assert "Scanners:    trivy" in out
        assert "isn't the recommended matcher" in out


class TestPlannedScanners:
    @pytest.mark.parametrize("requested,expected", [
        (None, ["grype", "osv", "trivy"]),
        ("grype", ["grype"]),
        ("bandit", []),
    ])
    def test_union_across_sboms(self, requested, expected):
        infos = [
            detect_sbom(FIXTURES / "syft-amzn2023.spdx.json"),
            detect_sbom(FIXTURES / "trivy-amzn2023.cdx.json"),
        ]
        names, _ = _sbom_planned_scanners(infos, ["grype", "osv", "trivy"], requested)
        assert names == expected
