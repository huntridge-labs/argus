"""Pick the vulnerability matcher for an SBOM from the tool that wrote it.

trivy and grype each read only some generators' SBOMs reliably. Measured
with the pinned tools (ADR-492, ADR-493):

- syft SBOMs: grype matches the OS packages; trivy reads the OS as
  ``none`` or ``amzn`` and skips them, and can't read Syft JSON at all
- trivy SBOMs: trivy matches them; grype can't map the ``amazon`` distro
  name and skips them

So a syft or grype SBOM goes to grype, a trivy SBOM goes to trivy, and an
SBOM from any other tool (or one that doesn't say) goes to both, with the
coverage guard (``argus.core.sbom_coverage``) flagging whichever skipped
the OS packages. osv-scanner isn't a matcher in this sense and always
runs. A scanner the user names explicitly always runs; picking one that
isn't recommended for the SBOM only adds a warning.

The accepted-generator table lives in docs/sbom-scanning.md.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable

from argus.core.sbom import SbomInfo
from argus.core.sbom_contents import Generator, read_generator

MATCHERS = ("grype", "trivy")

# Generator name -> the matcher that reads its SBOMs reliably.
GENERATOR_MATCHERS: dict[str, tuple[str, ...]] = {
    "syft": ("grype",),
    "grype": ("grype",),
    "trivy": ("trivy",),
}

DOCS_LINK = "docs/sbom-scanning.md#choosing-the-matcher"


@dataclass(frozen=True)
class MatcherChoice:
    """Which matcher(s) an SBOM should go to, and why."""

    matchers: tuple[str, ...]
    generator: Generator | None
    reason: str


def choose_matchers(info: SbomInfo) -> MatcherChoice:
    """Return the recommended matcher(s) for ``info``."""
    generator = read_generator(info)
    if info.format == "syft-json":
        # trivy can't decode the Syft JSON format, whoever wrote the file.
        return MatcherChoice(
            ("grype",), generator,
            f"Syft JSON SBOM ({_label(generator)}); trivy can't read this format",
        )
    known = GENERATOR_MATCHERS.get(generator.name) if generator else None
    if known:
        return MatcherChoice(known, generator, f"SBOM generated by {generator}")
    return MatcherChoice(
        MATCHERS, generator,
        f"SBOM generator {_label(generator)} has no recommended matcher; running both",
    )


def plan_sbom_scanners(
    info: SbomInfo,
    capable: Iterable[str],
    requested: list[str] | None,
) -> tuple[list[str], list[str]]:
    """Return ``(scanner names to run, notes to log)`` for one SBOM.

    ``capable`` is every registered SBOM-capable scanner. With no explicit
    request, the matchers the SBOM isn't recommended for are dropped (osv
    and any other non-matcher scanner stay). An explicit request runs as
    asked, minus names that can't read SBOMs; the notes say when a named
    matcher isn't the recommended one.
    """
    capable_set = set(capable)
    choice = choose_matchers(info)
    if requested is None:
        return _auto_plan(choice, capable_set)

    names = [name for name in requested if name in capable_set]
    notes = [
        _explicit_note(name, choice, info)
        for name in names
        if name in MATCHERS and name not in choice.matchers
    ]
    return names, notes


def _auto_plan(choice: MatcherChoice, capable: set[str]) -> tuple[list[str], list[str]]:
    available = [m for m in choice.matchers if m in capable]
    if not available:
        return sorted(capable), [
            f"{choice.reason}, but {', '.join(choice.matchers)} is not available; "
            "running every SBOM-capable scanner instead.",
        ]
    skipped = [m for m in MATCHERS if m in capable and m not in choice.matchers]
    names = sorted(n for n in capable if n not in skipped)
    notes = [f"{choice.reason}: matching with {', '.join(available)}"]
    if skipped:
        notes[0] += f", skipping {', '.join(skipped)} (see {DOCS_LINK})"
    return names, notes


def _explicit_note(name: str, choice: MatcherChoice, info: SbomInfo) -> str:
    recommended = " or ".join(choice.matchers)
    if name == "trivy" and info.format == "syft-json":
        return (
            "trivy can't read Syft JSON SBOMs and will fail on this file; "
            f"{recommended} is the recommended matcher. Running trivy as requested."
        )
    return (
        f"{name} isn't the recommended matcher for this SBOM ({choice.reason}); "
        f"{recommended} is. Running {name} as requested; if it skips the OS "
        "packages the result is marked incomplete."
    )


def _label(generator: Generator | None) -> str:
    return str(generator) if generator else "unknown"
